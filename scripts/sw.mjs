// Post-build: writes dist/sw.js (MIMARI §6). Hand-written, no Workbox: the shell is 2 pages + ~25 files.
// Precache = EN/TR tool pages, every /_astro file (island, CSS, workers), fonts, icons, engine manifests.
// Version = hash of every precached file, so any change gives a new sw.js -> install -> skipWaiting -> old shell cache deleted.
// Navigation is network-first (online always gets the fresh page; the cache is the offline fallback), assets cache-first.
// Engine files stay in load-wasm's own cache (convy-engines-v1): the SW only reads engine JS from it, and activate drops entries of
// engine versions no longer built.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
const DIST = process.env.DIST || 'dist';
const ls = (d) => (existsSync(`${DIST}/${d}`) ? readdirSync(`${DIST}/${d}`) : []);
const engines = ls('engines');
const files = [
  ...ls('_astro').map((f) => `/_astro/${f}`),
  ...ls('fonts').filter((f) => f.endsWith('.woff2')).map((f) => `/fonts/${f}`),
  ...ls('').filter((f) => /\.(png|ico|svg|webmanifest)$/.test(f)).map((f) => `/${f}`),
  ...engines.map((e) => `/engines/${e}/manifest.json`),
];
const pages = ['/', '/tr/'];
const h = createHash('sha256');
for (const p of [...pages.map((p) => `${p}index.html`), ...files]) h.update(p).update(readFileSync(DIST + p));
const V = h.digest('hex').slice(0, 10);
writeFileSync(`${DIST}/sw.js`, `// generated by scripts/sw.mjs
const V = 'convy-shell-${V}', P = ${JSON.stringify(pages)}, F = ${JSON.stringify(files)}, E = ${JSON.stringify(engines)};
const all = new Set([...P, ...F]);
self.addEventListener('install', (e) => e.waitUntil(caches.open(V).then((c) => c.addAll([...all].map((u) => new Request(u, { cache: 'no-cache' })))).then(() => self.skipWaiting())));
self.addEventListener('activate', (e) => e.waitUntil((async () => {
  for (const k of await caches.keys()) if (k.startsWith('convy-shell-') && k !== V) await caches.delete(k);
  if (await caches.has('convy-engines-v1')) { const c = await caches.open('convy-engines-v1'); for (const r of await c.keys()) if (!E.includes(new URL(r.url).pathname.split('/')[2])) await c.delete(r); }
  await self.registration.navigationPreload?.enable();
  await self.clients.claim();
})()));
self.addEventListener('fetch', (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== 'GET' || u.origin !== location.origin) return;
  if (r.mode === 'navigate') // preload is on for every navigation in scope, so every navigation must take it (SEO pages included)
    e.respondWith(Promise.resolve(e.preloadResponse).then((p) => p || fetch(r)).catch((err) => (P.includes(u.pathname) ? caches.match(u.pathname, { cacheName: V }) : Promise.reject(err))));
  else if (all.has(u.pathname)) e.respondWith(caches.match(u.pathname, { cacheName: V }).then((c) => c || fetch(r)));
  // engine JS loaded by URL (pdf.js modules, ffmpeg-core.js) comes from load-wasm's cache when saved; WebKit offline has no HTTP-cache fallback.
  // wasm parts are left alone: load-wasm reads them from the cache itself, and big downloads stay out of the worker.
  else if (u.pathname.startsWith('/engines/') && /\\.m?js$/.test(u.pathname)) e.respondWith(caches.match(r, { cacheName: 'convy-engines-v1' }).then((c) => c || fetch(r)));
});
`);
console.log(`${DIST}/sw.js: ${V}, ${pages.length} pages + ${files.length} files`);
